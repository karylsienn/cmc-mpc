"""Write an LTspice subcircuit of the MPC model.

The element list of circuit.mpc_netlist is the single source of truth. Every element value is
written as an expression of subcircuit parameters, and each expression is evaluated and compared
with the numeric netlist value before anything is written, so the exported circuit is the
verified one. Parameter names follow fit.Variant: LC CC RC LD CD RD CW, Lw Cwt Rw, Rcr Ccr,
Rrl Lrl, Cg, RDC, with a numeric suffix from the second branch on.

LTspice is case insensitive for parameters, so no two parameter names differ only in case.
"""
from __future__ import annotations

import re
from pathlib import Path

import numpy as np

from .circuit import mpc_netlist, port_y
from .io import write_s4p
from .mpc import MPCParams
from .setups import s_from_y


def param_map(p: MPCParams) -> dict[str, float]:
    v = dict(LC=p.LC, CC=p.CC, RC=p.RC, LD=p.LD, CD=p.CD, RD=p.RD, CW=p.CW)
    if p.lcr_w:
        v.update(Lw=p.lcr_w[0], Cwt=p.lcr_w[1], Rw=p.lcr_w[2])
    for i, (R, C) in enumerate(p.cr_branches):
        v.update({f"Rcr{i or ''}": R, f"Ccr{i or ''}": C})
    for i, (R, L) in enumerate(p.rl_branches):
        v.update({f"Rrl{i or ''}": R, f"Lrl{i or ''}": L})
    if p.Cg > 0:
        v["Cg"] = p.Cg
    if p.Rdc > 0:
        v["RDC"] = p.Rdc
    return v


_RULES = [  # (element name pattern, expression template), longest prefixes first
    (r"Rcr\d+_(\d+)", "Rcr{i}"), (r"Ccr\d+_(\d+)", "Ccr{i}"),
    (r"Rrl\d+_(\d+)", "Rrl{i}"), (r"Lrl\d+_(\d+)", "Lrl{i}"),
    (r"Lc\d", "LC/2"), (r"Ld\d", "LD/8"), (r"Cc\d", "CC"), (r"Rc\d", "RC"),
    (r"Cd\d", "CD"), (r"Rd\d", "RD"), (r"Cwt", "Cwt"), (r"Cw", "CW"), (r"Lw", "Lw"), (r"Rw", "Rw"),
    (r"Cg\d", "Cg"), (r"Rs\d", "RDC/2"),
]


def _expr(name: str) -> str:
    for pat, tpl in _RULES:
        m = re.fullmatch(pat, name)
        if m:
            return tpl.format(i=(m.group(1) if m.groups() and m.group(1) != "0" else ""))
    raise KeyError(name)


def subckt_text(p: MPCParams, name: str = "MPC", title: str = "") -> str:
    nl = mpc_netlist(p)
    params = param_map(p)
    node = lambda n: {"p1": "port1", "p2": "port2", "p3": "port3", "p4": "port4"}.get(n, n)
    lines = [f"* {title or 'MPC model'}, generated by cmc_mpc.ltspice from circuit.mpc_netlist",
             "* Inductor dots sit at the first node of each inductor.",
             f".subckt {name} port1 port2 port3 port4 params:",
             "+ " + " ".join(f"{k}={v:.6g}" for k, v in params.items())]
    for e in nl.elements:
        ex = _expr(e.name)
        val = eval(ex, {}, {k: float(f"{v:.6g}") for k, v in params.items()})
        assert abs(val - e.value) <= 1e-5 * abs(e.value), (e.name, ex, val, e.value)  # 6 significant digits
        lines.append(f"{e.name} {node(e.n1)} {node(e.n2)} {{{ex}}}")
    for i, c in enumerate(nl.couplings, 1):
        lines.append(f"K{i} {' '.join(c.inductors)} {c.k:g}")
    lines.append(f".ends {name}")
    return "\n".join(lines) + "\n"


def write_ltspice(p: MPCParams, outdir: str | Path, tag: str, title: str = "") -> tuple[Path, Path]:
    """Write MPC_<tag>.sub and the Python reference MPC_<tag>_python.s4p on 1 MHz to 1 GHz."""
    out = Path(outdir)
    out.mkdir(parents=True, exist_ok=True)
    sub = out / f"MPC_{tag}.sub"
    sub.write_text(subckt_text(p, f"MPC_{tag}", title))
    f = np.logspace(6, 9, 601)
    s4p = out / f"MPC_{tag}_python.s4p"
    write_s4p(s4p, f, s_from_y(port_y(mpc_netlist(p), f)), comment=f"{title or tag} reference from port_y")
    return sub, s4p


# ----------------------------------------------------------------------------
# Generic subcircuit. One topology with every optional part, unused parts switched off by value.
# ----------------------------------------------------------------------------

# Values that make a part electrically invisible in a 1 MHz to 1 GHz simulation.
OFF = dict(Lw=1e-12, Cwt=1e-15, Rw=1e6,        # LCR tank in YW becomes a short, so CW is a plain capacitor
           Rcr=1e6, Ccr=1e-18,                  # R-C branch carries no current
           Rrl=1e12, Lrl=1e-3,                  # R-L branch is open
           RDC=1e-6, Cg=1e-18)                  # no winding resistance, no ground capacitance

DEFAULT = MPCParams(LC=1.0e-2, CC=3e-12, RC=3e4, LD=7e-6, CD=3e-12, RD=1.6e4, CW=3e-12,
                    lcr_w=(OFF["Lw"], OFF["Cwt"], OFF["Rw"]), cr_branches=[(OFF["Rcr"], OFF["Ccr"])],
                    rl_branches=[(OFF["Rrl"], OFF["Lrl"])], Cg=OFF["Cg"], Rdc=OFF["RDC"], name="generic")


def generic_params(p: MPCParams) -> dict[str, float]:
    """Parameter values of the generic subcircuit that reproduce p. Needs at most one R-C and one R-L branch."""
    if len(p.cr_branches) > 1 or len(p.rl_branches) > 1:
        raise ValueError("the generic subcircuit has one R-C and one R-L branch")
    v = dict(LC=p.LC, CC=p.CC, RC=p.RC, LD=p.LD, CD=p.CD, RD=p.RD, CW=p.CW)
    v.update(dict(zip(("Lw", "Cwt", "Rw"), p.lcr_w if p.lcr_w else (OFF["Lw"], OFF["Cwt"], OFF["Rw"]))))
    v.update(dict(zip(("Rcr", "Ccr"), p.cr_branches[0] if p.cr_branches else (OFF["Rcr"], OFF["Ccr"]))))
    v.update(dict(zip(("Rrl", "Lrl"), p.rl_branches[0] if p.rl_branches else (OFF["Rrl"], OFF["Lrl"]))))
    v["Cg"] = p.Cg if p.Cg > 0 else OFF["Cg"]
    v["RDC"] = p.Rdc if p.Rdc > 0 else OFF["RDC"]
    return v


def mpc_from_generic(v: dict[str, float], name: str = "") -> MPCParams:
    """The all-parts MPCParams that the generic subcircuit simulates for parameter values v."""
    return MPCParams(LC=v["LC"], CC=v["CC"], RC=v["RC"], LD=v["LD"], CD=v["CD"], RD=v["RD"], CW=v["CW"],
                     lcr_w=(v["Lw"], v["Cwt"], v["Rw"]), cr_branches=[(v["Rcr"], v["Ccr"])],
                     rl_branches=[(v["Rrl"], v["Lrl"])], Cg=v["Cg"], Rdc=v["RDC"], name=name)


def generic_subckt_text() -> str:
    txt = subckt_text(DEFAULT, "MPC", "generic MPC model of a two-winding common-mode choke")
    note = ("* Parameters: LC CC RC (CM block), LD CD RD (DM block), CW and Lw Cwt Rw (interwinding path YW),\n"
            "* Rcr Ccr (R-C branch) and Rrl Lrl (R-L branch) across each CM winding, Cg (port to ground), RDC (winding resistance).\n"
            "* Unused parts are switched off by value: Lw=1e-12 shorts the LCR tank, Ccr=1e-18 and Rrl=1e12 remove the branches,\n"
            "* Cg=1e-18 and RDC=1e-6 remove ground capacitance and winding resistance. The defaults are a neutral starting point.\n")
    head, rest = txt.split("\n", 2)[:2], txt.split("\n", 2)[2]
    return "\n".join(head) + "\n" + note + rest


def preset_text(v: dict[str, float], name: str) -> str:
    """A subcircuit that instantiates the generic MPC with fitted values, plus the same values as one SpiceLine."""
    vals = " ".join(f"{k}={x:.6g}" for k, x in v.items())
    return (f"* {name}, fitted values for the generic MPC subcircuit. Needs .include MPC.sub\n"
            f".subckt {name} port1 port2 port3 port4\n"
            f"XMPC port1 port2 port3 port4 MPC {vals}\n"
            f".ends {name}\n")


def write_generic(outdir: str | Path) -> Path:
    out = Path(outdir); out.mkdir(parents=True, exist_ok=True)
    (out / "MPC.sub").write_text(generic_subckt_text())
    return out / "MPC.sub"


def write_preset(p: MPCParams, outdir: str | Path, tag: str) -> dict[str, Path]:
    """Write presets/MPC_<tag>.sub, presets/<tag>.spiceline.txt and a Python reference s4p of the generic circuit."""
    out = Path(outdir) / "presets"; out.mkdir(parents=True, exist_ok=True)
    v = {k: float(f"{x:.6g}") for k, x in generic_params(p).items()}
    (out / f"MPC_{tag}.sub").write_text(preset_text(v, f"MPC_{tag}"))
    (out / f"{tag}.spiceline.txt").write_text(" ".join(f"{k}={x:.6g}" for k, x in v.items()) + "\n")
    f = np.logspace(6, 9, 601)
    s4p = out / f"MPC_{tag}_python.s4p"
    write_s4p(s4p, f, s_from_y(port_y(mpc_netlist(mpc_from_generic(v)), f)), comment=f"{tag}, generic MPC with fitted values, reference from port_y")
    return {"sub": out / f"MPC_{tag}.sub", "line": out / f"{tag}.spiceline.txt", "s4p": s4p}
